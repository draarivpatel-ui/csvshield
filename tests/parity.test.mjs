/**
 * Cross-module parity tests: ESM source, generated CommonJS build and the
 * published TypeScript declaration surface must expose the same API.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';

import * as esm from '../src/index.mjs';
import * as esmCore from '../src/core.mjs';

const require = createRequire(import.meta.url);
const cjs = require('../cjs/index.cjs');
const cjsCore = require('../cjs/core.cjs');

const EXPORTS = [
  'VERSION',
  'CsvShieldError',
  'sanitizeCell',
  'stringifySafeCsv',
  'parseSafeCsv',
  'inspectCsv',
  'isSafeNegativeNumberValue',
  'findCsvTriggers',
];

test('ESM index exposes the full public API', () => {
  for (const name of EXPORTS) assert.equal(typeof esm[name], name === 'VERSION' ? 'string' : 'function', name);
});

test('CJS index exposes the full public API', () => {
  for (const name of EXPORTS) assert.equal(typeof cjs[name], name === 'VERSION' ? 'string' : 'function', name);
});

test('core subpath matches index exports in both module systems', () => {
  for (const name of EXPORTS) {
    assert.equal(esmCore[name], esm[name], `ESM core ${name}`);
    assert.equal(cjsCore[name], cjs[name], `CJS core ${name}`);
  }
});

test('version constants agree', () => {
  assert.equal(esm.VERSION, '1.0.0');
  assert.equal(esm.VERSION, cjs.VERSION);
});

test('ESM and CJS produce identical sanitization results', () => {
  const vectors = ['=1+1', '+1', '-1', '@A0', '\t=1', '|=1', ' =1', '﻿=1', 'ok\n=1', '-42'];
  const options = [{}, { mode: 'strip' }, { mode: 'preserve-numbers' }];
  for (const value of vectors) {
    for (const opts of options) {
      assert.equal(cjs.sanitizeCell(value, opts), esm.sanitizeCell(value, opts), `${JSON.stringify(value)} ${opts.mode}`);
    }
  }
});

test('ESM and CJS produce identical parse and stringify output', () => {
  const input = 'name,value\n"=cmd|calc",-42\nplain,3\n';
  assert.deepEqual(cjs.parseSafeCsv(input, { hasHeader: true }), esm.parseSafeCsv(input, { hasHeader: true }));
  const rows = [{ a: '=1', b: 2 }, { a: '-3', b: null }];
  assert.equal(cjs.stringifySafeCsv(rows), esm.stringifySafeCsv(rows));
});

test('CsvShieldError is a real Error in both builds', () => {
  const a = new esm.CsvShieldError('x', { code: 'ERR_CSV_OPTION', row: 2 });
  const b = new cjs.CsvShieldError('x', { code: 'ERR_CSV_OPTION', row: 2 });
  assert.ok(a instanceof Error);
  assert.ok(b instanceof Error);
  assert.equal(a.name, 'CsvShieldError');
  assert.deepEqual(a.toJSON(), b.toJSON());
});

test('error classes reject CJS instances from ESM instanceof checks as expected', () => {
  assert.equal(new cjs.CsvShieldError('x') instanceof esm.CsvShieldError, false);
});

test('package exports map declares import, require and types for both entries', () => {
  const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
  assert.deepEqual(pkg.dependencies, {});
  assert.deepEqual(pkg.devDependencies, { 'fast-check': '4.10.3' });
  for (const key of ['.', './core']) {
    const entry = pkg.exports[key];
    assert.ok(entry.import.endsWith('.mjs'), key);
    assert.ok(entry.require.endsWith('.cjs'), key);
    assert.ok(entry.types.endsWith('.d.ts'), key);
  }
});

test('declaration file declares every public function and type', () => {
  const dts = readFileSync(new URL('../types/index.d.ts', import.meta.url), 'utf8');
  for (const name of EXPORTS.filter((n) => n !== 'VERSION')) {
    assert.ok(dts.includes(name), `missing declaration: ${name}`);
  }
  for (const type of ['PolicyMode', 'SanitizeOptions', 'CsvParseOptions', 'CsvStringifyOptions', 'InspectionReport']) {
    assert.ok(dts.includes(type), `missing type: ${type}`);
  }
});

test('generated CJS files carry the generated banner', () => {
  for (const file of ['../cjs/index.cjs', '../cjs/core.cjs']) {
    const src = readFileSync(new URL(file, import.meta.url), 'utf8');
    assert.match(src, /Generated by scripts\/build-cjs\.mjs/);
  }
});
